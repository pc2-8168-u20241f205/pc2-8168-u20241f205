/// <summary>Exposes the disbursement order creation endpoint.</summary>
/// <remarks>Author: Candy Milagros Vizcarra Mamani.</remarks>
[ApiController]
[Route("api/v1/disbursement-orders")]
[Produces("application/json")]
public sealed class DisbursementOrdersController(IDisbursementOrderCommandService commandService) : ControllerBase
{
    /// <summary>Creates a disbursement order.</summary>
    /// <param name="resource">Order details supplied by the client.</param>
    /// <param name="cancellationToken">Request cancellation token.</param>
    /// <returns>The created order, or a localized error response.</returns>
    [HttpPost]
    [EndpointSummary("Create a disbursement order")]
    [EndpointDescription("Creates and persists a disbursement order. The identifier is generated by the database.")]
    [ProducesResponseType(typeof(DisbursementOrderResource), StatusCodes.Status201Created)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status409Conflict)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status500InternalServerError)]
    public async Task<IActionResult> Create([FromBody] CreateDisbursementOrderResource resource,
        CancellationToken cancellationToken)
    {
        var command = CreateDisbursementOrderCommandAssembler.ToCommand(resource);
        var result = await commandService.HandleAsync(command, cancellationToken);
        if (result is Result<DisbursementOrder, CreateDisbursementOrderError>.Success success)
        {
            var response = DisbursementOrderResourceAssembler.ToResource(success.Value);
            return Created($"/api/v1/disbursement-orders/{response.Id}", response);
        }

        var error = ((Result<DisbursementOrder, CreateDisbursementOrderError>.Failure)result).Error;
        var (status, title, detail) = LocalizedErrors.Resolve(error.Code, error.Message, HttpContext.RequestServices);
        return Problem(statusCode: status, title: title, detail: detail);
    }
}
